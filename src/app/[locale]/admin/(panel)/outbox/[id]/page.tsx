import { eq } from "drizzle-orm";
import { notFound } from "next/navigation";
import { getTranslations, setRequestLocale } from "next-intl/server";
import { getDb } from "@/db";
import { emailOutbox } from "@/db/schema";
import { Link } from "@/i18n/navigation";
import { formatDateTime } from "@/lib/money";

const templateLabels: Record<string, string> = {
  "order-confirmation": "templateOrder",
  contact: "templateContact",
  "reset-password": "templateReset",
  "password-changed": "templatePasswordChanged",
  "verify-email": "templateVerify",
  welcome: "templateWelcome",
};

export default async function AdminOutboxDetailPage({
  params,
}: PageProps<"/[locale]/admin/outbox/[id]">) {
  const { locale, id } = await params;
  setRequestLocale(locale);

  const [t, row] = await Promise.all([
    getTranslations("Admin"),
    (async () => {
      const db = await getDb();
      return db.query.emailOutbox.findFirst({ where: eq(emailOutbox.id, id) });
    })(),
  ]);
  if (!row) notFound();

  const templateKey = templateLabels[row.template];
  const statusLabel =
    row.status === "sent"
      ? t("statusSent")
      : row.status === "failed"
        ? t("statusFailed")
        : t("statusLogged");

  return (
    <>
      <header className="admin-topbar">
        <h1>{row.subject}</h1>
        <div className="admin-topbar-actions">
          <Link href="/admin/outbox" className="text-link">
            {t("backToOutbox")}
          </Link>
        </div>
      </header>

      <div className="admin-content">
        <section className="admin-card">
          <dl className="info-list">
            <div>
              <dt>{t("to")}</dt>
              <dd>{row.to}</dd>
            </div>
            <div>
              <dt>{t("template")}</dt>
              <dd>{templateKey ? t(templateKey) : row.template}</dd>
            </div>
            <div>
              <dt>{t("sentAt")}</dt>
              <dd>{formatDateTime(row.createdAt, locale)}</dd>
            </div>
            <div>
              <dt>{t("status")}</dt>
              <dd>
                <span
                  className="badge"
                  data-tone={
                    row.status === "sent"
                      ? "green"
                      : row.status === "failed"
                        ? "red"
                        : "muted"
                  }
                >
                  {statusLabel}
                </span>
              </dd>
            </div>
            {row.providerId ? (
              <div>
                <dt>{t("providerId")}</dt>
                <dd className="muted small">{row.providerId}</dd>
              </div>
            ) : null}
          </dl>

          {row.error ? <p className="form-error">{row.error}</p> : null}

          <p className="admin-section-title">{t("htmlVersion")}</p>
          <div
            className="outbox-html"
            // biome-ignore lint/security/noDangerouslySetInnerHtml: the HTML is generated by our own email templates
            dangerouslySetInnerHTML={{ __html: row.html }}
          />

          <p className="admin-section-title">{t("textVersion")}</p>
          <pre className="outbox-text">{row.text}</pre>
        </section>
      </div>
    </>
  );
}
